/**
 * 判断モデル（Clef / Clef-flash）の比較に使う試験セット（#330）。
 *
 * `expected` は「誰でも見られるタイピング練習サイトの公開一覧に載せてよいか」の正解。
 * `gray` はどちらに倒れても困らないもので、成績には数えず確率だけを見る。
 *
 * - **入力（テーマ名・最適化する音）は厳しく見る。** 物騒な題材でも、普通の題材なら通したい
 * - **生成お題は緩く見る。** 物騒・身体・歴史の語や、物語の中の暴力は通したい
 *
 * 生成お題は**テーマごとのまとまり**（`group`）で持つ。本番は1つのテーマの1ラウンド分を
 * まとめて判定するので、同じ依頼に並ぶ候補もそれに似せる。だめなものは、モデルが
 * 混ぜてきそうなもの（性的な語・蔑称・実際の加害のそそのかし）を各テーマに少しずつ入れる。
 * NG 語リスト（`NG_WORDS`）にある語も混ぜ、リストと AI を合わせた成績も見る。
 */

export type ModerationKind = "theme" | "constraint" | "word" | "sentence" | "long";
export type Expected = "ok" | "ng" | "gray";

export interface ModerationCase {
  kind: ModerationKind;
  text: string;
  expected: Expected;
  /** 普通の題材だが、物騒・身体・歴史などの語を含むもの。誤検出を見る */
  tricky?: boolean;
  /** 生成お題のテーマ。同じテーマの候補を1回の依頼にまとめる */
  group?: string;
}

interface Labeled {
  ok?: readonly string[];
  tricky?: readonly string[];
  ng?: readonly string[];
  gray?: readonly string[];
}

function cases(kind: ModerationKind, labeled: Labeled, group?: string): ModerationCase[] {
  const make = (texts: readonly string[] | undefined, expected: Expected, tricky = false) =>
    (texts ?? []).map((text) => ({ kind, text, expected, tricky, group }));
  return [
    ...make(labeled.ok, "ok"),
    ...make(labeled.tricky, "ok", true),
    ...make(labeled.ng, "ng"),
    ...make(labeled.gray, "gray"),
  ];
}

function topic(
  group: string,
  parts: { words: Labeled; sentences: Labeled; longs: Labeled },
): ModerationCase[] {
  return [
    ...cases("word", parts.words, group),
    ...cases("sentence", parts.sentences, group),
    ...cases("long", parts.longs, group),
  ];
}

