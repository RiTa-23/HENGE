/**
 * 出題の形式。**`kind`（テーマ／最適化）とは直交する軸。**
 *
 * `kind` に値を足す形にすると、テーマ「福岡」が一覧に2つ並ぶことになる。
 * 同じテーマを2つの形式で遊びたいので、プールの側（`prompts.form`）で分ける。
 */
export type PromptForm = "sentence" | "word";

/** 1プレイ = 15問。進捗ドットの数もこれに合わせる */
export const PLAY_SIZE = 15;

/**
 * 単語の1プレイ = 30問。
 *
 * 単語は1語あたり8打前後しかないため、15問だと120打・20秒ほどで終わる。
 * 30問で約240打になり、短文1プレイ（約330打）に近い手応えになる。
 */
export const PLAY_SIZE_WORD = 30;

/** その形式の1プレイの問題数。**画面もAPIもこれを通す**（15を直接書かない） */
export function playSize(form: PromptForm): number {
  return form === "word" ? PLAY_SIZE_WORD : PLAY_SIZE;
}

/**
 * 在庫の目標水準。残り（総生成数 − オフセット）がこれを下回ったら補充をキックする。
 *
 * 30 は「2プレイ分」。1プレイで15問消費するため、補充が終わる前にもう一度
 * 遊ばれても在庫が足りる。ここを下げるとバッファが1プレイ分を割り、
 * 「もう一度」を押した時点で在庫切れに当たりやすくなる。
 */
export const STOCK_TARGET = 30;

/**
 * 単語の在庫目標。**短文と同じ30にする（2プレイ分の60にしない）。**
 *
 * 単語は1プレイ30問なので、素直に数えれば2プレイ分は60になる。**それをやると
 * プールを作った直後の1回目の補充で必ず失敗する。** 補充が1回で作れるのは
 * 最大40件（20件×2ラウンド）で、在庫0から60は埋められない。目標未達は
 * `generation_status = 'difficult'` を立てる条件なので、**普通のテーマが
 * 「生成困難」の印を付けられ、以後の補充が止まる**。
 *
 * 30なら1回の補充で埋まる。単語のバッファは1プレイ分になるが、届かない目標を
 * 掲げて補充そのものを止めるより良い。
 */
export const STOCK_TARGET_WORD = 30;

/** その形式の在庫目標。下回ったら補充をキックする */
export function stockTarget(form: PromptForm): number {
  return form === "word" ? STOCK_TARGET_WORD : STOCK_TARGET;
}

/**
 * 1日の生成上限（JST基準）。**回数ではなく消費ニューロンで数える。**
 *
 * 回数で数えると1回の重さを見ないことになる。実測では1ラウンド（20件）が
 * 約6.5ニューロンで、2ラウンド回る呼び出しはその倍かかる。守りたいのは
 * Workers AI の無料枠（**アカウント全体で1日10,000ニューロン**）の方なので、
 * 消費量そのもので数える。
 *
 * 500 は上の実測で1日約40〜75回にあたり、旧上限（50回/日）と同じ桁に収まる。
 * アカウント全体に対しては、枠を使い切る利用者20人分。
 *
 * 判定は Next.js 側、記録（加算）は Hono 側で行う。この定数を参照するのは
 * 判定と残数計算を担う Next.js 側のみでよい。Hono 側は渡された許可フラグを
 * 信頼するだけ（ポリシー値を持たない）。
 */
export const DAILY_NEURON_LIMIT = 500;

/**
 * 生成ロックのTTL（秒）。**KVの下限と同じ60秒。**
 *
 * 在庫不足のプレイは、ロックがあれば `GENERATION_IN_PROGRESS` を返して待たせる。
 * **`GENERATION_WAIT_LIMIT_MS` より必ず短く保つこと**（`session.test.ts` で固定）。
 * TTLの方が長いと、生成が打ち切られた後も「待てば解決する」と言い続けたまま
 * クライアントが先に諦め、**待たせた末にエラーを見せる**ことになる。
 *
 * 60秒で足りる根拠は、背景補充が `waitUntil` の中で走り、レスポンス送信から
 * 30秒で打ち切られること。生きているロックが30秒強より長生きする必要はない。
 *
 * **バックエンドとフロントで別々に持たない。** 2つの値の大小がこの仕組みの前提で、
 * 離して置くと片方だけ動かしたときに静かに壊れる。
 */
export const THEME_LOCK_TTL_SECONDS = 60;

/**
 * 「生成中」で待たせる上限（ミリ秒）。これを超えたらエラーとして見せる。
 *
 * ロックのTTL（上記）より長くする。待っている間にロックが期限切れになれば、
 * 次の引き直しで本当の状態（在庫があるか、本当に尽きたか）が返る。
 */
export const GENERATION_WAIT_LIMIT_MS = 90_000;
