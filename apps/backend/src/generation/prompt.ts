import type { ThemeKind } from "@henge/shared";

/**
 * 生成プロンプト。**全モデルで共通のものを1つだけ持つ。**
 *
 * 呼び出しはステートレスなので、2回目のバッチは1回目が何を作ったか知らない。
 * 既存お題を「これと似たものを作るな」という文脈として渡す設計だったが、
 * いまは外して試している（`INCLUDE_EXISTING_PROMPTS` 参照）。
 */

/** 既存お題を何件遡って持ってくるか。プロンプトの文脈と、完全一致の重複除去に使う */
export const EXISTING_CONTEXT_SIZE = 30;

/**
 * 既存お題をプロンプトに載せるか。**いまは載せない（2026-09-06 から試行中）。**
 *
 * 直近30件を「これと似た内容・似た言い回しは避けろ」という否定の文脈として
 * 渡していたが、**モデルが内容ではなく形式の方に引きずられている疑いがある。**
 * few-shot と同じで、否定で添えても例示は例示として効くため、お題の型
 * （文の長さ・構文・主語の立て方）が既存に揃っていく。「慣れが生じない」ことが
 * このサービスの目的なので、型が揃うのは重複そのものより悪い。
 *
 * **外しても同じ文が二度入ることはない。** 完全一致の重複は batch.ts の `seen`
 * （`new Set(input.existing)`）が読み取得の前に無料で弾いており、そちらは
 * 生きたまま。効き目が変わるのは「言い回しの近い別の文」だけ。
 *
 * 戻すときはここを true にする。判断は却下率・重複率の実測（Phase 8）で行う。
 */
const INCLUDE_EXISTING_PROMPTS: boolean = false;

const SYSTEM = [
  "あなたは日本語タイピング練習用の短文を作る職人です。",
  "指示された条件を厳密に守り、余計な説明を一切書かず、短文だけを出力します。",
].join("");

function rules(count: number): string[] {
  return [
    `- ちょうど${count}個の短文を作る`,
    "- 1行に1文ずつ、番号や記号を付けずに出力する",
    "- 使ってよい文字は、ひらがな・カタカナ・漢字と、次の5種類の記号だけ",
    "  、 。 ー ！ ？",
    "- 「」（）〜・：やアルファベット・数字・空白は絶対に使わない",
    "- 1文はひらがなに直して8〜18文字程度。**これを超えると長すぎて拒否される**（打鍵数は35打まで。1かなは平均2打程度なので、20文字の文は40打前後になる）",
    "- 文ごとに、テーマの異なる側面（定義・種類・例・使い方・歴史など）を扱う",
    "- 漢字をかならず1つ以上使う。ひらがなだけの文にしない",
    "- 意味の通る自然な日本語にする",
  ];
}

/**
 * テーマモード固有の指示。**テーマ名で文を始めさせない。**
 *
 * テーマ「博多」で「博多の〜」が20文並び、テーマ「TypeScript」では読みの
 * 「タイプスクリプトは〜」が20文並んだ（実測）。 **「テーマ名を使うのは
 * 最大2文まで」という全体数えの指示は効かなかった** —「含む」モードの実測
 * （語頭○個まで→文頭21/21）と同じ。一方、文字種や漢字のような
 * **1文ごとに判定できる指示は守られる**。そこで文頭禁止という局所ルールにする。
 * 文面は「博多の名物は〜」→「名物は〜」と語を落とすだけで回収できる。
 */
function themeRules(name: string): string[] {
  const rules = [
    `- どの文も、テーマの名前「${name}」（とその読み）で書き始めない。名前は文の途中にだけ使う`,
  ];
  // 名前がアルファベットのテーマ。モデルは名前をそのまま書きたがるが、
  // アルファベットは文字種検査で却下されるため、カタカナ読みに置き換えさせる
  if (/[a-zA-Z]/u.test(name)) {
    rules.push(
      "- アルファベットは絶対に書かない。テーマの名前はカタカナの読み（例: TypeScript→タイプスクリプト）に置き換えて、文の途中にだけ使う",
    );
  }
  return rules;
}

/**
 * 「含む」モード固有の指示。
 *
 * 何も言わないと、モデルは指定文字を文頭に置いた語を毎回作る（実測で8文すべてが文頭）。
 * しかも文頭に置くために「ざいあん」「ざいじん」のような**存在しない語を作る**。
 *
 * **曖昧な指示はほとんど効かない。**「散らす」「なおよい」では実測で文頭6/8だった。
 * 効くのは数えられる形にしたときだけなので、この関数の指示はすべて個数で書く。
 *
 * 偏りは3つの軸で出る。**それぞれ別の指示が要る**（1つにまとめると効かない）。
 *
 * | 軸 | 放っておくと | 指示 |
 * |---|---|---|
 * | 語の中の位置 | 文頭の語に集中する | 1文ずつ判定できる形で「書き出しに入れない」と言う |
 * | 品詞 | ほぼ名詞になる | 動詞・形容詞・副詞の最低数を決める |
 * | 出現回数 | 1文に1回だけ | 2回以上入れる文の数を決める |
 * | 言い回し | 同じ型を量産する | 全部違う語で書き始めさせる＋書き出しの重複を却下する |
 *
 * **個数で言えば従う、とは限らない。**「語頭に来る文は4個まで」は完全に無視され、
 * 実測で文頭21/21だった。全体を数えさせる指示は守られないので、位置の指示は
 * 1文ずつ判定できる形（「書き出しの語に入れない」）に書く。
 */
function constraintRules(char: string, count: number): string[] {
  /** 動詞に入れる文の数 */
  const verbTarget = Math.max(2, Math.floor(count / 4));
  /** 形容詞・副詞に入れる文の数 */
  const modifierTarget = Math.max(2, Math.floor(count / 5));
  /**
   * 1文に2回以上入れる文の数。
   *
   * **半数（10個）は珍しい音で無理がある。**「ぴ」のように語彙の少ない音だと、
   * 1文に2語入れようとして却下が増え、15問に届かず生成そのものが失敗した（実測）。
   * 1/3なら、よくある音では余裕を持って超えてくる（「し」で実測56%）。
   */
  const twiceTarget = Math.ceil(count / 3);

  return [
    `- すべての文に「${char}」を必ず入れる。表記に出ていなくても、読み仮名に含まれていればよい`,
    // **「○個までにする」は効かなかった**（実測で文頭21/21）。全体を数えさせる指示は
    // 守られないので、1文ずつ判定できる形に書く
    `- どの文も、「${char}」を含まない語から書き始める。「${char}」は2語目以降に置く`,
    // 位置だけ縛ると、今度は文末の助詞に逃げる。「し」を指定したとき、実測で
    // 「〜したし」「〜面白し」のように接続助詞として付けるだけの文を量産した
    // （日本語としても壊れる）。**語の一部として使わせる**ことを明示する
    `- 「${char}」は、名詞・動詞・形容詞など意味を持つ語の一部として使う。` +
      `助詞や語尾として付け足すだけの使い方をしない`,
    `- 文を途中で終わらせない。「〜し」「〜が」「〜けど」のような接続で終わる文を作らない`,
    `- 「${char}」を入れる語の品詞を散らす。名詞だけにしない。` +
      `動詞に入る文を${verbTarget}個以上、形容詞または副詞に入る文を${modifierTarget}個以上作る`,
    // **擬音語・擬態語を勧めてはいけない**。「しんしんと」のような語を1つ見つけると、
    // 20個中14個をそれで埋めてくる（実測）。2回入れる手段は語を2つ使う方に寄せる
    `- ${twiceTarget}個以上の文では、1文の中に「${char}」を2回以上入れる。` +
      `「${char}」を含む語を2つ使うか、「${char}」を2回含む語（擬音語・擬態語など）を使う`,
    `- ${count}個すべてを違う語で書き始める。同じ語や同じ組み立ての文を使い回さない`,
    `- 実在する言葉だけを使う。「${char}」を入れるために存在しない語を作らない`,
  ];
}

export function buildGenerationPrompt(input: {
  kind: ThemeKind;
  /** テーマ名、または「含む文字」 */
  name: string;
  count: number;
  /** 重複回避の文脈。直近の既存お題 */
  existing: string[];
}): { system: string; user: string } {
  const subject =
    input.kind === "theme"
      ? `テーマ「${input.name}」に沿った短文を作ってください。`
      : `読み仮名に「${input.name}」を含む短文を作ってください。表記に現れていなくても、読みに含まれていれば構いません。`;

  const lines = [subject, "", "条件:", ...rules(input.count)];

  if (input.kind === "theme") lines.push(...themeRules(input.name));

  if (input.kind === "constraint") lines.push(...constraintRules(input.name, input.count));

  if (INCLUDE_EXISTING_PROMPTS && input.existing.length > 0) {
    lines.push(
      "",
      "次はすでに作成済みの短文です。これらと似た内容・似た言い回しは避けてください。",
      ...input.existing.map((text) => `- ${text}`),
    );
  }

  return { system: SYSTEM, user: lines.join("\n") };
}

/** モデルの出力を1文ずつに切る。番号や箇条書き記号が付いていても落とす */
export function parseGeneratedLines(output: string): string[] {
  return output
    .split("\n")
    .map((line) =>
      line
        .trim()
        .replace(/^[-*・\d]+[.)、.]?\s*/u, "")
        .trim(),
    )
    .filter((line) => line.length > 0);
}
