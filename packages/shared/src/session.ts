/**
 * 出題の形式。**`kind`（テーマ／最適化）とは直交する軸。**
 *
 * `kind` に値を足す形にすると、テーマ「福岡」が一覧に2つ並ぶことになる。
 * 同じテーマを2つの形式で遊びたいので、プールの側（`prompts.form`）で分ける。
 */
export type PromptForm = "sentence" | "word" | "long";

/**
 * すべての形式。画面の札やタブ、ロックの掃除など「形式ぶん並べる」ところで使う。
 *
 * **並びは画面の並び（単語 → 短文 → 長文）。** 短いものから長いものへ並べる方が
 * 分かりやすい。既定の形式（URLにクエリが無いとき）は短文のままで、並びとは別の話。
 */
export const PROMPT_FORMS: readonly PromptForm[] = ["word", "sentence", "long"];

/**
 * 文字列を形式として読む。**既定は短文。未知の値も短文に倒す。**
 *
 * 形式を持たない古いURL・古いクライアントがそのまま短文で動くようにするため。
 * 知らない値を通すと、存在しないプールを引くことになる。
 * `form === "word" ? "word" : "sentence"` を各所に書かせない（形式が増えるたびに
 * 書き漏れる）。
 */
export function parsePromptForm(value: string | null | undefined): PromptForm {
  return value === "word" || value === "long" ? value : "sentence";
}

/** 1プレイ = 15問。進捗ドットの数もこれに合わせる */
export const PLAY_SIZE = 15;

/**
 * 単語の1プレイ = 20問。
 *
 * 単語は1語あたり8打前後なので、15問だと120打・20秒ほどで終わってしまう。
 * 20問で約160打あり、短文1プレイ（約330打）の半分ほどの手応えになる。
 *
 * **本当は30問にしたい。やめたのは読み仮名の取得が外部APIだから。**
 * Yahoo APIは1語につき外部サブリクエストを1回使い、Workers無料プランの上限は
 * 1実行あたり50回。生成は20件×2ラウンド＝40件が上限なので、目標30問は
 * **採用率75%を要求する**ことになり、実際には届かない。届かなければ1プレイ分が
 * 揃わず、利用者は「単語のお題を作る」を2〜3回押すことになる（1回につき約13
 * ニューロン）。20問なら40件中20件（採用率50%）で埋まり、たいてい1回で始まる。
 *
 * **`getReading()` を形態素解析ライブラリへ差し替えたら30問に戻す**
 * （`docs/05-generation.md`）。外部サブリクエストを使わなくなれば上限が外れ、
 * 1回の生成で30問ぶんを作れるようになる。
 */
export const PLAY_SIZE_WORD = 20;

/**
 * 長文の1プレイ = **1本**。
 *
 * 1本が読み仮名150〜220文字（打鍵250〜450）のまとまった文章で、短文1プレイ
 * （約330打）と同じ程度の手応えになる。複数本にすると1本ごとに巻物を切り替える
 * ことになり、「文章を通しで打つ」という形式の意味が薄れる。
 */
export const PLAY_SIZE_LONG = 1;

/** その形式の1プレイの問題数。**画面もAPIもこれを通す**（15を直接書かない） */
export function playSize(form: PromptForm): number {
  if (form === "word") return PLAY_SIZE_WORD;
  if (form === "long") return PLAY_SIZE_LONG;
  return PLAY_SIZE;
}

/**
 * 在庫の目標水準。残り（総生成数 − オフセット）がこれを下回ったら補充をキックする。
 *
 * 30 は「2プレイ分」。1プレイで15問消費するため、補充が終わる前にもう一度
 * 遊ばれても在庫が足りる。ここを下げるとバッファが1プレイ分を割り、
 * 「もう一度」を押した時点で在庫切れに当たりやすくなる。
 */
export const STOCK_TARGET = 30;

/**
 * 単語の在庫目標。**短文と同じ30にする。**
 *
 * 1プレイ20問なので1.5プレイ分にあたる。**2プレイ分（40）にしない。**
 * 補充が1回で作れるのは最大40件（20件×2ラウンド）で、在庫0から40を埋めるには
 * 採用率100%が要る。目標未達は `generation_status = 'difficult'` を立てる条件
 * なので、**普通に作れているテーマに「生成困難」の印が付き、以後の補充が止まる**。
 *
 * 1プレイの問題数を増やすときは、**この値が1回の補充で埋まるか**を必ず見直すこと。
 */
export const STOCK_TARGET_WORD = 30;

/**
 * 長文の在庫目標。**3本（3プレイ分）。**
 *
 * 1回の補充で作れるのは最大10本（5本×2ラウンド）なので、在庫0からでも埋まる。
 * 単語と同じく、目標が1回の補充の上限を超えると「生成困難」の印が誤って立つ。
 */
export const STOCK_TARGET_LONG = 3;

/** その形式の在庫目標。下回ったら補充をキックする */
export function stockTarget(form: PromptForm): number {
  if (form === "word") return STOCK_TARGET_WORD;
  if (form === "long") return STOCK_TARGET_LONG;
  return STOCK_TARGET;
}

/**
 * 1日の生成上限（JST基準）。**回数ではなく消費ニューロンで数える。**
 *
 * 回数で数えると1回の重さを見ないことになる。実測では1ラウンド（20件）が
 * 約6.5ニューロンで、2ラウンド回る呼び出しはその倍かかる。守りたいのは
 * Workers AI の無料枠（**アカウント全体で1日10,000ニューロン**）の方なので、
 * 消費量そのもので数える。
 *
 * 500 は上の実測で1日約40〜75回にあたり、旧上限（50回/日）と同じ桁に収まる。
 * アカウント全体に対しては、枠を使い切る利用者20人分。
 *
 * 判定は Next.js 側、記録（加算）は Hono 側で行う。この定数を参照するのは
 * 判定と残数計算を担う Next.js 側のみでよい。Hono 側は渡された許可フラグを
 * 信頼するだけ（ポリシー値を持たない）。
 */
export const DAILY_NEURON_LIMIT = 500;

/**
 * 生成ロックのTTL（秒）。**KVの下限と同じ60秒。**
 *
 * 在庫不足のプレイは、ロックがあれば `GENERATION_IN_PROGRESS` を返して待たせる。
 * **`GENERATION_WAIT_LIMIT_MS` より必ず短く保つこと**（`session.test.ts` で固定）。
 * TTLの方が長いと、生成が打ち切られた後も「待てば解決する」と言い続けたまま
 * クライアントが先に諦め、**待たせた末にエラーを見せる**ことになる。
 *
 * 60秒で足りる根拠は、背景補充が `waitUntil` の中で走り、レスポンス送信から
 * 30秒で打ち切られること。生きているロックが30秒強より長生きする必要はない。
 *
 * **バックエンドとフロントで別々に持たない。** 2つの値の大小がこの仕組みの前提で、
 * 離して置くと片方だけ動かしたときに静かに壊れる。
 */
export const THEME_LOCK_TTL_SECONDS = 60;

/**
 * 「生成中」で待たせる上限（ミリ秒）。これを超えたらエラーとして見せる。
 *
 * ロックのTTL（上記）より長くする。待っている間にロックが期限切れになれば、
 * 次の引き直しで本当の状態（在庫があるか、本当に尽きたか）が返る。
 */
export const GENERATION_WAIT_LIMIT_MS = 90_000;
