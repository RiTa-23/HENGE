/**
 * 読みを読み違えやすいので、お題に出さない語。**NG 語（`ng-words.ts`）とは目的が違うので混ぜない。**
 * NG 語は語そのものを出したくない。こちらは語に問題はなく、読みを正しく取れないだけ。
 *
 * ユーザー辞書の1行では直せない語を載せる。読みが文脈で割れる語は、辞書の行で片方に寄せると
 * もう片方を壊す（辛い＝からい／つらい、抱く＝だく／いだく、市場＝いちば／しじょう）。お題は
 * 捨てて作り直せるので、読み分けられない語は無理に読まない。**いずれも本番のお題の誤読から
 * 足した**（2026-11）。機場・站は読みの問題ではなく、モデルが混ぜた中国語の表記である。
 */

/** 本文への部分一致で見る語句 */
const ANYWHERE = ["風穴が開", "審査に通っ", "の下で", "機場"];

const KANJI = String.raw`[\p{Script=Han}々]`;

const PATTERN = new RegExp(
  [
    ...ANYWHERE,
    // **兵站 は日本語なので見ない。** 共通語彙リストに入っている
    "(?<!兵)站",
    // **前に漢字が続くときは見ない。** 塩辛い・甘辛い・介抱 は読みが割れない
    `(?<!${KANJI})辛[いくかさそ]`,
    `(?<!${KANJI})抱[いくかけこ]`,
    // **複合語は見ない。** 魚市場・市場調査 は読みが割れない
    `(?<!${KANJI})市場(?!${KANJI})`,
  ].join("|"),
  "u",
);

/** 生成したお題に、読みを読み違えやすい語が入っているか。**最適化・テーマの全形式で使う。** */
export function containsReadingProneWord(text: string): boolean {
  return PATTERN.test(text);
}
