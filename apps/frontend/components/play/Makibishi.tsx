import "./ninja.css";

/**
 * 撒菱（ミス表示）。ミスしたローマ字の**真上**に置く。
 *
 * **CSSはこのファイルで読む**（Shuriken と同じ理由。読み込みを呼び出し側に
 * 任せると、色も位置も当たらないまま素の四角が出る）。
 *
 * 形は四方に棘が出た撒菱。上へ長い棘が1本、下へ開いた脚が2本、そのあいだから
 * 手前へ短い棘が1本出る。`clip-path` の多角形をやめてSVGにしたのは、
 * **棘ごとに長さと角度を変えないと、ぱっと見できらめきの記号に見えてしまう**ため
 * （等間隔・等長の棘は撒菱ではなく星になる）。
 *
 * 色は朱より暗く鈍い赤（`--color-makibishi`）。手前の棘だけは、脚と重なって
 * 溶けないよう**地の色で細く縁取って**切り分ける（色は足していない）。
 */
export function Makibishi() {
  return (
    <svg className="makibishi" viewBox="0 0 24 24" aria-hidden="true">
      <g fill="currentColor">
        {/* 上向きの棘。踏むと刺さる側なので、いちばん長く見せる */}
        <polygon points="12,0.8 14.3,12.2 9.7,12.2" />
        {/* 接地する2本の脚 */}
        <polygon points="2.6,19.8 13.1,14.3 10.6,10.7" />
        <polygon points="21.4,19.8 13.4,10.7 10.9,14.3" />
        {/* 手前へ出る棘。脚のあいだから覗く */}
        <polygon
          points="12,21.8 13.9,12.2 10.1,12.2"
          stroke="var(--color-sumi)"
          strokeWidth="0.7"
          strokeLinejoin="round"
        />
        {/* 棘の付け根。これが無いと4本がばらばらの三角に見える */}
        <circle cx="12" cy="12.2" r="2.7" />
      </g>
    </svg>
  );
}
